-- Consulta de solo lectura para ejecutar en el servidor con acceso a SISCOB y CobAuto.
-- Muestra a los usuarios activos de las carteras Compartamos y sus asignaciones CRM.
-- PERMISO_RADAR_INDIVIDUAL = NULL significa que se aplica el permiso del perfil.

SELECT
    LTRIM(RTRIM(U.USUARIO)) AS DNI_USUARIO,
    LTRIM(RTRIM(ISNULL(U.Nombres, ''))) AS NOMBRES,
    LTRIM(RTRIM(ISNULL(U.Apellidos, ''))) AS APELLIDOS,
    U.TipoUsuario AS PERFIL,
    U.IDCARTERA AS CARTERA_PRINCIPAL,
    CASE WHEN A.USUARIO IS NOT NULL AND A.FLG_ACTIVO = 1 THEN 1 ELSE 0 END AS CUENTA_CRM_ACTIVA,
    V.PERMITIDO AS PERMISO_RADAR_INDIVIDUAL,
    (SELECT COUNT(DISTINCT C.idcartera)
     FROM CobAuto.dbo.CRM_SUPERVISOR_CARTERA C
     WHERE LTRIM(RTRIM(C.usuario)) COLLATE DATABASE_DEFAULT =
           LTRIM(RTRIM(U.USUARIO)) COLLATE DATABASE_DEFAULT
       AND C.activo = 1 AND C.idcartera <> U.IDCARTERA) AS CARTERAS_ADICIONALES_ACTIVAS,
    CASE WHEN EXISTS (
        SELECT 1 FROM CobAuto.dbo.CRM_SUPERVISOR_CARTERA C
        WHERE LTRIM(RTRIM(C.usuario)) COLLATE DATABASE_DEFAULT =
              LTRIM(RTRIM(U.USUARIO)) COLLATE DATABASE_DEFAULT
          AND C.idcartera = 128 AND C.activo = 1
    ) THEN 1 ELSE 0 END AS CARTERA_128_ADICIONAL
FROM SISCOB.dbo.USUARIO U
LEFT JOIN CobAuto.dbo.CRM_USUARIO_ACCESO A
    ON A.USUARIO COLLATE DATABASE_DEFAULT = LTRIM(RTRIM(U.USUARIO)) COLLATE DATABASE_DEFAULT
LEFT JOIN CobAuto.dbo.CRM_USUARIO_VISTA V
    ON V.USUARIO COLLATE DATABASE_DEFAULT = LTRIM(RTRIM(U.USUARIO)) COLLATE DATABASE_DEFAULT
   AND V.VISTA = 'clientes'
WHERE U.IDCARTERA IN (124, 126, 128, 133, 144)
  AND LTRIM(RTRIM(ISNULL(U.Estado, ''))) = 'A'
ORDER BY U.IDCARTERA, U.Apellidos, U.Nombres, U.USUARIO;
